#!/usr/bin/env python3
"""lock.py — lock and unlock chapters; the one writer of Fact Check/Locks.md.

    tools/lock.py status              # every chapter and its lock state
    tools/lock.py status 02           # one chapter
    tools/lock.py unlock 02 --by production --note "the author reopened it: the Hamilton quotation"
    tools/lock.py lock 02 --by production [--note "..."]

WHAT A LOCK IS

    A lock says a chapter is finished. A chapter marked 🔒 reports itself as
    verified and finished to every tool that asks, so an edit made while it is
    marked 🔒 inherits a verification it never had. The order is: unlock, edit,
    relock, push. The first and third steps are the ones that get skipped,
    because only the middle one feels like work.

    Reopening a locked chapter is the author's decision. Say why in chat, get
    the author's ruling, then record it here with `unlock --note`.

ONE FILE, ONE WRITER

    `Fact Check/Locks.md` holds a table:

        | chapter | state | date | by | note |

    with state 🔒 or 🔓, one row per lock or unlock, newest last. The last row
    for a chapter is its state; a chapter with no row is unlocked. The rows
    above it are the chapter's lock history, and the event log holds each
    change as well (a `file.written` event with the before and after, and a
    `lock.changed` event when the log accepts that kind).

    In the system this kit comes from, a lock was stamped in four places (the
    chapter, the Punch List, the book outline, the project state file), and a
    chapter was once unlocked in three of them and left locked in the fourth.
    The lock gate then read the four as out of sync. One file means there is
    nothing to fall out of sync, and this script is the only thing that writes
    it.

THE GATE

    `lock` runs `tools/check-lock-ready.sh NN` and refuses unless it passes.
    A chapter in `[workflow] out_of_workflow` (book.toml) can be neither locked
    nor unlocked: no tool touches it until the author says so.

EXIT CODES
    0  done (or nothing to change)
    1  refused: the gate failed, the chapter is out of workflow, or a note is missing
    2  usage or setup error
"""
import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bookconfig as B  # noqa: E402

TOOLS = Path(__file__).resolve().parent
LOCKED, UNLOCKED = "🔒", "🔓"
ROLES = ("author", "fact-checker", "editor", "production", "managing-editor", "systems")
HEADER = "| chapter | state | date | by | note |"
ROW_RE = re.compile(r"^\|\s*(\d+)\s*\|\s*(🔒|🔓)\s*\|([^|]*)\|([^|]*)\|(.*)\|\s*$")

TEMPLATE = """# Locks

The one record of whether a chapter is locked (`Methodology/Chapter Close-Out Procedure.md`). **Do not edit this file by hand.** It is changed only by `tools/lock.py lock NN` (which refuses unless `tools/check-lock-ready.sh NN` passes) and `tools/lock.py unlock NN` (which records the reason). One row per lock or unlock, newest last; the last row for a chapter is its state. A chapter with no row is unlocked.

**Columns:** `chapter` (two digits) · `state` (🔒 locked or 🔓 unlocked) · `date` (UTC) · `by` (the role, and the author's ruling for an unlock) · `note` (for an unlock, the reason; for a lock, the gate's result).

{header}
|---|---|---|---|---|
"""


def today() -> str:
    return datetime.datetime.now(datetime.timezone.utc).date().isoformat()


def role_ok(role: str) -> str:
    r = role.strip().lower().replace(" ", "-")
    if r == B.AUTHOR_ACTOR.lower():
        r = "author"
    if r not in ROLES:
        print(f"--by must name a role: {', '.join(ROLES)} (got {role!r}).")
        raise SystemExit(2)
    return r


def read_rows():
    """{chapter: (state, date, by, note)}, the last row for each chapter, and the file's text."""
    if not B.LOCKS.exists():
        return {}, ""
    text = B.LOCKS.read_text(encoding="utf-8")
    rows = {}
    for line in text.splitlines():
        m = ROW_RE.match(line)
        if m:
            rows[int(m.group(1))] = (m.group(2), m.group(3).strip(),
                                     m.group(4).strip(), m.group(5).strip())
    return rows, text


def render(text: str, n: int, row) -> str:
    """The file with one row appended for chapter n. Rows are never edited:
    the rows above are the chapter's lock history."""
    if not text.strip() or HEADER not in text:
        text = TEMPLATE.format(header=HEADER)
    state, date, by, note = row
    clean = lambda x: x.replace("|", "/").replace("\n", " ").strip()
    return text.rstrip("\n") + f"\n| {n:02d} | {state} | {date} | {clean(by)} | {clean(note)} |\n"


def write(n: int, row, role: str):
    """Log, then write. A lock change that is not logged is not made."""
    try:
        import vaultlog
    except ImportError as e:
        raise SystemExit(f"tools/vaultlog.py could not be loaded ({e}). "
                         f"A lock change that is not logged is not made.")
    _, text = read_rows()
    new_text = render(text, n, row)
    state, _, _, note = row
    word = "locked" if state == LOCKED else "unlocked"
    vaultlog.write_file(B.LOCKS, new_text, tool="lock.py",
                        why=f"Ch{n:02d} {word} by {role}: {note}".rstrip(": "))
    if "lock.changed" in getattr(vaultlog, "KINDS", ()):
        vaultlog.append("lock.changed", actor=role, chapter=n, state=word, note=note)


def out_of_workflow(n: int) -> bool:
    if n in B.OUT_OF_WORKFLOW:
        print(f"Ch{n:02d} is out of workflow (book.toml [workflow] out_of_workflow). "
              f"No tool locks or unlocks it until the author takes it off that list.")
        return True
    return False


def cmd_status(args) -> int:
    rows, _ = read_rows()
    nums = [args.chapter] if args.chapter is not None else sorted(
        set(rows) | {B.chapter_number(p) for p in B.chapter_files()} - {None})
    if not nums:
        print("No chapters found.")
        return 0
    for n in nums:
        if n in B.OUT_OF_WORKFLOW:
            print(f"  Ch{n:02d}  out of workflow")
            continue
        if n in rows:
            state, date, by, note = rows[n]
            word = "LOCKED" if state == LOCKED else "UNLOCKED"
            print(f"  Ch{n:02d}  {state} {word:<8} {date}  by {by}" + (f"  — {note}" if note else ""))
        else:
            print(f"  Ch{n:02d}  {UNLOCKED} never locked")
    return 0


def cmd_unlock(args) -> int:
    n = args.chapter
    if out_of_workflow(n):
        return 1
    role = role_ok(args.by)
    rows, _ = read_rows()
    if n not in rows or rows[n][0] == UNLOCKED:
        print(f"Ch{n:02d} is not locked. Nothing to change.")
        return 0
    note = (args.note or "").strip()
    if not note and sys.stdin.isatty():
        note = input(f"Why is Ch{n:02d} reopening, and when did the author rule it? ").strip()
    if not note:
        print("unlock needs the reason (--note): why the chapter is reopening, and the author's "
              "ruling. Reopening a lock is the author's decision.")
        return 1
    write(n, (UNLOCKED, today(), f"{role}, on the author's ruling", note), role)
    print(f"Ch{n:02d} 🔓 UNLOCKED by {role}. Edit, then relock with: tools/lock.py lock {n:02d} --by {role}")
    return 0


def cmd_lock(args) -> int:
    n = args.chapter
    if out_of_workflow(n):
        return 1
    role = role_ok(args.by)
    if B.chapter_file(n) is None:
        print(f"No chapter {n:02d} in {B.CHAPTERS}.")
        return 2
    gate = TOOLS / "check-lock-ready.sh"
    if not gate.exists():
        print("tools/check-lock-ready.sh is missing. No lock without the gate.")
        return 1
    r = subprocess.run([sys.executable, str(gate), f"{n:02d}"], capture_output=True, text=True)
    if r.returncode != 0:
        sys.stdout.write(r.stdout)
        sys.stderr.write(r.stderr)
        print(f"\nREFUSED: Ch{n:02d} did not pass check-lock-ready.sh (exit {r.returncode}). "
              f"Locks.md is unchanged.")
        return 1
    rows, _ = read_rows()
    if rows.get(n, ("",))[0] == LOCKED:
        print(f"Ch{n:02d} is already locked ({rows[n][1]}). Nothing to change.")
        return 0
    note = "check-lock-ready.sh passed" + (f"; {args.note.strip()}" if (args.note or "").strip() else "")
    write(n, (LOCKED, today(), role, note), role)
    print(f"Ch{n:02d} 🔒 LOCKED by {role}.")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="lock.py", description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("status")
    s.add_argument("chapter", nargs="?", type=int)
    for name in ("unlock", "lock"):
        p = sub.add_parser(name)
        p.add_argument("chapter", type=int)
        p.add_argument("--by", required=True, help="the role making the change: " + ", ".join(ROLES))
        p.add_argument("--note", default="")
    try:
        args = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    return {"status": cmd_status, "unlock": cmd_unlock, "lock": cmd_lock}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
